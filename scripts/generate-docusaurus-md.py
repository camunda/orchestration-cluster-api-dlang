#!/usr/bin/env python3
"""Convert the SDK README and generated surface into Docusaurus markdown.

Mirrors the PHP / Rust sibling generators. camunda-docs copies the output of
this script into `docs/apis-tools/d-sdk[.md]`.

Input:
    README.md
    docs/api-reference.md / docs/semantic-types.md  (from generate.py hook 06)
    external-spec/bundled/spec-metadata.json

Output (gitignored; regenerated by `make docs-md`):
    docs-md/d-sdk.md
    docs-md/d-sdk/*.md
    docs-md/d-sdk/api-reference/

Usage:
    python3 scripts/generate-docusaurus-md.py [--validate-links]
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
META = ROOT / "external-spec" / "bundled" / "spec-metadata.json"
DOCS_MD = ROOT / "docs-md"
SECTION = DOCS_MD / "d-sdk"
API_REF = SECTION / "api-reference"

GITHUB_REF = os.environ.get("DOCS_SDK_REF") or "main"
GITHUB_BLOB = f"https://github.com/camunda/orchestration-cluster-api-dlang/blob/{GITHUB_REF}"
GITHUB_TREE = f"https://github.com/camunda/orchestration-cluster-api-dlang/tree/{GITHUB_REF}"

LANDING_ID = "d-sdk"
LANDING_TITLE = "D SDK (Technical Preview)"
API_REFERENCE_POSITION = 100
LANDING_PAGE_DEPTH = 1
SECTION_PAGE_DEPTH = 2
API_REFERENCE_DEPTH = 3

URL_PATH_OVERRIDES = {
    "camunda-api-rest": "orchestration-cluster-api-rest",
}

TECH_PREVIEW_BANNER = (
    "\n:::caution Technical Preview\n"
    "The D SDK is a **technical preview**. Its API surface may still evolve and "
    "changes may not follow semantic versioning. Pin an exact version if you need "
    "stability.\n"
    ":::\n"
)

CURATED_NAMES = {
    "getTopology": "getTopologyOp",
    "createDeployment": "createDeploymentOp",
    "createDocument": "createDocumentOp",
    "createDocuments": "createDocumentsOp",
}


def escape_yaml(s: str) -> str:
    return s.replace('"', '\\"')


def slugify(title: str) -> str:
    slug = re.sub(r"[^a-z0-9\s_-]", "", title.lower())
    slug = re.sub(r"\s+", "-", slug.strip())
    return re.sub(r"-+", "-", slug)


def landing_frontmatter() -> str:
    return (
        "---\n"
        f"id: {LANDING_ID}\n"
        f'title: "{escape_yaml(LANDING_TITLE)}"\n'
        f'sidebar_label: "{escape_yaml(LANDING_TITLE)}"\n'
        "sidebar_position: 1\n"
        "mdx:\n"
        "  format: md\n"
        "---\n\n"
    )


def section_frontmatter(page_id: str, title: str, position: int) -> str:
    return (
        "---\n"
        f"id: {page_id}\n"
        f'title: "{escape_yaml(title)}"\n'
        f'sidebar_label: "{escape_yaml(title)}"\n'
        f"sidebar_position: {position}\n"
        "mdx:\n"
        "  format: md\n"
        "---\n\n"
    )


def strip_cut_sections(content: str) -> str:
    return re.sub(r"<!-- docs:cut:start -->.*?<!-- docs:cut:end -->\n?", "", content, flags=re.S)


def strip_html_comments(content: str) -> str:
    return re.sub(r"^[ \t]*<!--.*?-->[ \t]*\n", "", content, flags=re.M | re.S)


def strip_contributing(content: str) -> str:
    return re.sub(r"\n## Contributing\b.*", "", content, flags=re.S)


def clean_empty_lines(content: str) -> str:
    return re.sub(r"\n{4,}", "\n\n\n", content)


def split_by_h2(content: str) -> tuple[str, list[tuple[str, str]]]:
    parts = re.split(r"(?=^## )", content, flags=re.M)
    preamble = parts[0] if parts else ""
    sections: list[tuple[str, str]] = []
    for part in parts[1:]:
        m = re.match(r"^## (.+)\n", part)
        if m:
            sections.append((m.group(1).strip(), part))
    return preamble, sections


def build_anchor_map(sections: list[tuple[str, str]]) -> dict[str, str]:
    mapping: dict[str, str] = {}
    for title, body in sections:
        page_slug = slugify(title)
        for heading in re.findall(r"^#{2,6}\s+(.+)$", body, flags=re.M):
            mapping[slugify(heading.strip())] = page_slug
    return mapping


def rewrite_internal_anchors(content: str, current_slug: str, anchor_map: dict[str, str]) -> str:
    def repl(m: re.Match[str]) -> str:
        target = anchor_map.get(m.group(2))
        if target and target != current_slug:
            return f"[{m.group(1)}]({target}.md#{m.group(2)})"
        return m.group(0)

    return re.sub(r"\[([^\]]+)\]\(#([^)]+)\)", repl, content)


def promote_headings(content: str) -> str:
    def repl(m: re.Match[str]) -> str:
        hashes = m.group(1)
        if len(hashes) > 1:
            return "#" * (len(hashes) - 1) + " " + m.group(2)
        return m.group(0)

    return re.sub(r"^(#{1,6}) (.+)$", repl, content, flags=re.M)


def rewrite_docs_links(content: str, depth: int) -> str:
    prefix = "../" * depth

    def repl(m: re.Match[str]) -> str:
        url_path = m.group(2).rstrip("/")
        for old, new in URL_PATH_OVERRIDES.items():
            url_path = url_path.replace(old, new)
        return f"[{m.group(1)}]({prefix}{url_path}.md)"

    return re.sub(
        r"\[([^\]]*)\]\(https?://docs\.camunda\.io/docs/(?:next/)?(.*?)\)",
        repl,
        content,
    )


def rewrite_repo_links(content: str) -> str:
    def repl(m: re.Match[str]) -> str:
        text, target = m.group(1), m.group(2)
        if target.endswith(".md") and "/" not in target:
            return m.group(0)
        clean = target.lstrip("./")
        base = (
            GITHUB_TREE
            if clean.endswith("/") or "." not in Path(clean).name
            else GITHUB_BLOB
        )
        return f"[{text}]({base}/{clean})"

    return re.sub(r"\[([^\]]+)\]\((?!https?://|#|mailto:|\.\./)([^)\s]+)\)", repl, content)


def inject_tech_preview_banner(content: str) -> str:
    m = re.search(r"^#\s+.+$", content, flags=re.M)
    if not m:
        return content
    pos = m.end()
    return content[:pos] + "\n" + TECH_PREVIEW_BANNER + content[pos:]


def reset_output() -> None:
    if SECTION.exists():
        shutil.rmtree(SECTION)
    landing = DOCS_MD / "d-sdk.md"
    if landing.exists():
        landing.unlink()
    API_REF.mkdir(parents=True, exist_ok=True)


def write_readme_pages() -> None:
    content = README.read_text(encoding="utf-8")
    content = strip_cut_sections(content)
    content = strip_html_comments(content)
    content = strip_contributing(content)
    content = clean_empty_lines(content)
    content = re.sub(r"^#\s+.*$", f"# {LANDING_TITLE}", content, count=1, flags=re.M)
    content = re.sub(r"^\[!\[.*?\)$\n?", "", content, flags=re.M)
    content = content.strip() + "\n"

    preamble, sections = split_by_h2(content)
    anchor_map = build_anchor_map(sections)

    landing = rewrite_docs_links(preamble, LANDING_PAGE_DEPTH)
    landing = rewrite_repo_links(landing)
    landing = inject_tech_preview_banner(landing)
    (DOCS_MD / "d-sdk.md").write_text(
        landing_frontmatter() + clean_empty_lines(landing).strip() + "\n",
        encoding="utf-8",
    )
    print("  Wrote landing page docs-md/d-sdk.md")

    for i, (title, body) in enumerate(sections):
        slug = slugify(title)
        position = i + 2
        section = rewrite_docs_links(body, SECTION_PAGE_DEPTH)
        section = rewrite_internal_anchors(section, slug, anchor_map)
        section = rewrite_repo_links(section)
        page = promote_headings(section)
        page = inject_tech_preview_banner(page)
        (SECTION / f"{slug}.md").write_text(
            section_frontmatter(slug, title, position)
            + clean_empty_lines(page).strip()
            + "\n",
            encoding="utf-8",
        )
        print(f"  Wrote section docs-md/d-sdk/{slug}.md")


def write_api_reference() -> None:
    meta = json.loads(META.read_text(encoding="utf-8"))
    operations = list(meta["operations"])
    keys = list(meta.get("semanticKeys") or [])

    by_tag: dict[str, list[dict]] = {}
    for op in operations:
        tag = (op.get("tags") or ["Untagged"])[0]
        by_tag.setdefault(tag, []).append(op)

    index = section_frontmatter("d-sdk-api-reference", "Overview", 0)
    index += "# API reference\n\n"
    index += (
        ":::caution Technical Preview\n"
        "The D SDK is a **technical preview**. Its API surface may still evolve and "
        "changes may not follow semantic versioning. Pin an exact version if you need "
        "stability.\n:::\n\n"
    )
    index += (
        f"The SDK exposes **{len(operations)} operations** across **{len(by_tag)} API groups**. "
        "Every operation is a method on `CamundaClient`:\n\n"
        "```d\n"
        "auto client = CamundaClient.fromEnv();\n"
        "auto topology = client.topology();\n"
        "```\n\n"
        "| API group | Operations |\n| --- | --- |\n"
    )
    for tag in sorted(by_tag):
        slug = slugify(tag)
        index += f"| [{tag}]({slug}.md) | {len(by_tag[tag])} |\n"
    index += "| [Domain type system](domain-type-system.md) | — |\n"
    (API_REF / "index.md").write_text(index + "\n", encoding="utf-8")

    for position, tag in enumerate(sorted(by_tag), start=1):
        slug = slugify(tag)
        ops = by_tag[tag]
        page = section_frontmatter(slug, tag, position)
        page += f"# {tag}\n\n"
        page += (
            f"`CamundaClient` — {len(ops)} operations in this group. "
            "Call any of these directly on the client.\n\n"
        )
        for op in ops:
            name = CURATED_NAMES.get(op["operationId"], op["operationId"])
            method = (op.get("method") or "get").upper()
            path = op.get("path") or "/"
            summary = (op.get("summary") or "").strip()
            line = f"- `{name}()` (`{method} {path}`)"
            if summary:
                line += f" — {summary}"
            page += line + "\n"
        (API_REF / f"{slug}.md").write_text(page + "\n", encoding="utf-8")

    sem = section_frontmatter("domain-type-system", "Domain type system", len(by_tag) + 1)
    sem += "# Domain type system\n\n"
    sem += (
        "Each identifier is a distinct D struct in `camunda.generated.keys`. "
        "Construct with `tryNew` (validates) or `assumeExists` (side-load).\n\n"
        "| Type | Pattern | Length | Description |\n| --- | --- | --- |\n"
    )
    for key in keys:
        name = key["name"]
        constraints = key.get("constraints") or {}
        pattern = constraints.get("pattern")
        pat = f"`{pattern}`" if pattern else "—"
        min_len = constraints.get("minLength")
        max_len = constraints.get("maxLength")
        if min_len is not None and max_len is not None:
            length = f"{min_len}–{max_len}"
        elif max_len is not None:
            length = f"≤ {max_len}"
        elif min_len is not None:
            length = f"≥ {min_len}"
        else:
            length = "—"
        desc = (key.get("description") or "").replace("\n", " ").replace("|", "\\|").strip()
        sem += f"| `{name}` | {pat} | {length} | {desc} |\n"
    (API_REF / "domain-type-system.md").write_text(sem + "\n", encoding="utf-8")

    (API_REF / "_category_.json").write_text(
        json.dumps({"label": "API Reference", "position": API_REFERENCE_POSITION}, indent=2)
        + "\n",
        encoding="utf-8",
    )
    print(
        f"  Wrote API reference: index + {len(by_tag)} groups + domain-type-system "
        f"({len(operations)} operations)"
    )


def validate_links() -> None:
    broken: list[str] = []
    pages = [DOCS_MD / "d-sdk.md", *SECTION.glob("*.md"), *API_REF.glob("*.md")]
    for page in pages:
        text = page.read_text(encoding="utf-8")
        for m in re.finditer(r"\[([^\]]*)\]\((?!https?://|#|mailto:)([^)]+)\)", text):
            target = m.group(2).split("#", 1)[0]
            if target == "" or target.startswith("../"):
                continue
            resolved = (page.parent / target).resolve()
            if not resolved.exists():
                broken.append(f"{page.name} -> {m.group(2)}")
    if broken:
        print("Broken relative links:", file=sys.stderr)
        for b in broken:
            print(f"  - {b}", file=sys.stderr)
        sys.exit(1)
    print("  Link validation passed.")


def main() -> int:
    validate = "--validate-links" in sys.argv
    reset_output()
    write_readme_pages()
    write_api_reference()
    if validate:
        validate_links()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
